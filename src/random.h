// Walks the table, wrapping around at the end.
struct RandomSeries {
    u32 index;
};

inline u32 random_next(RandomSeries& series) {
    u32 res = k_random_number_table[series.index];
    series.index = (series.index + 1) % static_cast<u32>(std::size(k_random_number_table));
    return res;
}

// A value in [0, count).
inline u32 random_choice(RandomSeries& series, u32 count) {
    return random_next(series) % count;
}

